"""
Export the estimated circuit paths of a backbone model to Google Earth (KMZ)
plus a per-circuit path table (Markdown and CSV).

Every backbone and AWS circuit is its own path:
  * circuit 1 on a link follows the direct great-circle route;
  * each further circuit follows its own diverse route, bowed out further
    each time (1, 2, 3 x spacing), inland in North America.
The model's circuit_paths() supplies the paths, route km and one-way latency.

Run (from the repo root):  python lowlatency-plan1/export_kmz.py [model.py] [output_dir]
Writes lowlatency_plan1_paths.kmz, circuit_paths.md and circuit_paths.csv.
"""
import os
import sys
import csv
import zipfile
import importlib.util
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
model_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "lowlatency_plan1_model.py")
out_dir = sys.argv[2] if len(sys.argv) > 2 else HERE
os.makedirs(out_dir, exist_ok=True)

spec = importlib.util.spec_from_file_location("model", model_path)
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

rows = m.circuit_paths()
EN = "–"
# KML colours are aabbggrr; one per circuit index
COLORS = ["ffb4771f", "ff2827d6", "ff2ca02c", "ff0e7fff", "ffbd6794"]


def route_name(r):
    k = r["circuit"] - 1
    return "direct" if k == 0 else f"diverse {k}"


def link_name(r):
    return f"{r['a']}{EN}{r['z']}"


# --- table rows -------------------------------------------------------------
table = []
for r in rows:
    table.append({
        "Link": link_name(r),
        "Type": "Backbone" if r["kind"] == "backbone" else "AWS on-ramp",
        "Circuit": f"{r['circuit']}/{r['of']}",
        "Route": route_name(r),
        "Lateral offset km": f"{r['offset_km']:+.0f}" if r["offset_km"] else "0",
        "Great-circle km": f"{r['gc_km']:,.0f}",
        "Est. route km": f"{r['route_km']:,.0f}",
        "One-way ms": m.fmt_ms(r["ms"]),
        "KMZ placemark": f"{link_name(r)} c{r['circuit']}",
    })

with open(os.path.join(out_dir, "circuit_paths.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(table[0]))
    w.writeheader()
    w.writerows(table)

cols = list(table[0])
md = [f"# {m.TITLE} {EN} estimated circuit paths", "",
      "Generated by `export_kmz.py`. Open `lowlatency_plan1_paths.kmz` in Google Earth "
      "to see every path; each row below is one placemark.", "",
      "**Assumptions**", "",
      f"- Circuit 1 on each link takes the direct great-circle route. Every further circuit "
      f"takes its own diverse route, bowed out further each time (diverse 1, 2, 3). "
      f"Each step is {m.DIVERSITY:.0%} of the link distance "
      f"({m.MIN_SPACING_KM:.0f}{EN}{m.MAX_SPACING_KM:.0f} km). In North America the bow goes "
      f"inland, toward the middle of the continental US, so alternates stay over land.",
      f"- Est. route km = geometric path length {chr(215)} {m.ROUTE_FACTOR} route factor "
      f"(fiber slack and rights-of-way).",
      f"- One-way ms = route km {chr(215)} {m.FIBER_US_PER_KM} {chr(181)}s/km "
      f"(light in single-mode fiber). Propagation only; equipment, queueing and "
      f"serialization delay are excluded.",
      "- AWS on-ramps run to the assumed region: "
      + "; ".join(f"{k} = {v[2]}" for k, v in m.CLOUD_LOCATIONS.items())
      + ". Internet hand-offs are local and have no path.", "",
      "| " + " | ".join(cols) + " |",
      "|" + "|".join("---:" if c in ("Lateral offset km", "Great-circle km", "Est. route km", "One-way ms")
                     else "---" for c in cols) + "|"]
for t in table:
    md.append("| " + " | ".join(t[c] for c in cols) + " |")
with open(os.path.join(out_dir, "circuit_paths.md"), "w") as f:
    f.write("\n".join(md) + "\n")

# --- KML --------------------------------------------------------------------
def coords(pts):
    return " ".join(f"{lon:.5f},{lat:.5f},0" for lat, lon in pts)


k = ['<?xml version="1.0" encoding="UTF-8"?>',
     '<kml xmlns="http://www.opengis.net/kml/2.2"><Document>',
     f"<name>{escape(m.TITLE)} {EN} estimated circuit paths</name>",
     "<description>Circuit 1 direct, further circuits on diverse routes. "
     f"Route km = path x {m.ROUTE_FACTOR}; {m.FIBER_US_PER_KM} us/km fiber.</description>",
     '<Style id="site"><IconStyle><scale>1.1</scale><Icon><href>'
     'http://maps.google.com/mapfiles/kml/shapes/placemark_circle.png</href></Icon></IconStyle>'
     '<LabelStyle><scale>1.0</scale></LabelStyle></Style>',
     '<Style id="cloud"><IconStyle><scale>1.0</scale><Icon><href>'
     'http://maps.google.com/mapfiles/kml/shapes/square.png</href></Icon></IconStyle></Style>']
for i, c in enumerate(COLORS):
    k.append(f'<Style id="c{i + 1}"><LineStyle><color>{c}</color><width>3</width></LineStyle></Style>')

k.append("<Folder><name>Sites</name>")
for s, (lat, lon, desc) in m.LOCATIONS.items():
    k.append(f"<Placemark><name>{escape(s)}</name><description>{escape(desc)}</description>"
             f"<styleUrl>#site</styleUrl><Point><coordinates>{lon:.5f},{lat:.5f},0</coordinates>"
             "</Point></Placemark>")
k.append("</Folder><Folder><name>AWS regions</name>")
for s, (lat, lon, desc) in m.CLOUD_LOCATIONS.items():
    k.append(f"<Placemark><name>{escape(s)}</name><description>{escape(desc)}</description>"
             f"<styleUrl>#cloud</styleUrl><Point><coordinates>{lon:.5f},{lat:.5f},0</coordinates>"
             "</Point></Placemark>")
k.append("</Folder>")

for kind, title in (("backbone", "Backbone circuits"), ("cloud", "AWS on-ramp circuits")):
    k.append(f"<Folder><name>{title}</name>")
    links = {}
    for r, t in zip(rows, table):
        if r["kind"] == kind:
            links.setdefault(link_name(r), []).append((r, t))
    for name, items in links.items():
        lo = min(r["ms"] for r, _ in items)
        hi = max(r["ms"] for r, _ in items)
        span = m.fmt_ms(lo) if len(items) == 1 else f"{m.fmt_ms(lo)}{EN}{m.fmt_ms(hi)}"
        k.append(f"<Folder><name>{escape(name)} ({len(items)} ckt, {span} ms)</name>")
        for r, t in items:
            desc = (f"Circuit {t['Circuit']} &#8211; {t['Route']}<br/>"
                    f"Great-circle {t['Great-circle km']} km<br/>"
                    f"Est. route {t['Est. route km']} km<br/>"
                    f"One-way {t['One-way ms']} ms")
            k.append(f"<Placemark><name>{escape(t['KMZ placemark'])} &#8211; {t['One-way ms']} ms</name>"
                     f"<description><![CDATA[{desc}]]></description>"
                     f"<styleUrl>#c{min(r['circuit'], len(COLORS))}</styleUrl>"
                     f"<LineString><tessellate>1</tessellate><coordinates>{coords(r['path'])}"
                     "</coordinates></LineString></Placemark>")
        k.append("</Folder>")
    k.append("</Folder>")
k.append("</Document></kml>")

kmz = os.path.join(out_dir, "lowlatency_plan1_paths.kmz")
with zipfile.ZipFile(kmz, "w", zipfile.ZIP_DEFLATED) as z:
    z.writestr("doc.kml", "\n".join(k))
print(f"Wrote {kmz}: {len(rows)} circuit paths, {len(m.LOCATIONS)} sites")
print(f"Wrote {os.path.join(out_dir, 'circuit_paths.md')} and circuit_paths.csv")
